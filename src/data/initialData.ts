export function getCurrentPeriodInfo(periods: SchedulePeriod[]): CurrentPeriodInfo {
  const now = new Date();
  const day = now.getDay(); // 0 = Sun, 1 = Mon ... 6 = Sat
  const isWeekday = day >= 1 && day <= 5;

  const currentMinutes = now.getHours() * 60 + now.getMinutes();

  if (!isWeekday || periods.length === 0) {
    return {
      isSchoolHours: false,
      period: null,
      timeRemaining: null,
      minutesRemaining: null,
    };
  }

  for (const p of periods) {
    const [startH, startM] = p.startTime.split(':').map(Number);
    const [endH, endM] = p.endTime.split(':').map(Number);
    const periodStart = startH * 60 + startM;
    const periodEnd = endH * 60 + endM;

    if (currentMinutes >= periodStart && currentMinutes < periodEnd) {
      const minutesRemaining = periodEnd - currentMinutes;
      const hours = Math.floor(minutesRemaining / 60);
      const mins = minutesRemaining % 60;
      const timeRemaining = hours > 0 ? `${hours}h ${mins}m` : `${mins} min`;

      return {
        isSchoolHours: true,
        period: p,
        timeRemaining,
        minutesRemaining,
      };
    }
  }

  return {
    isSchoolHours: false,
    period: null,
    timeRemaining: null,
    minutesRemaining: null,
  };
}
